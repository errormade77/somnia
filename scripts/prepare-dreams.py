"""Create local, silent square previews. Originals are never modified.

Usage: python3 scripts/prepare-dreams.py SOURCE_DIRECTORY --ffmpeg /path/to/ffmpeg
"""
import argparse
import concurrent.futures
import json
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
parser.add_argument('--ffmpeg', default='ffmpeg')
args = parser.parse_args()
output = Path(__file__).resolve().parents[1] / 'assets' / 'dreams'
output.mkdir(parents=True, exist_ok=True)
sources = sorted(args.source.glob('*.mp4'))
if not sources:
    raise SystemExit('No MP4 files found')

def run(arguments):
    subprocess.run([args.ffmpeg, '-hide_banner', '-loglevel', 'error', '-y', *arguments], check=True)

def encode(item):
    index, source = item
    name = f'dream-{index + 1:02}'
    probe = subprocess.run([args.ffmpeg, '-hide_banner', '-i', str(source)], capture_output=True, text=True).stderr
    hours, minutes, seconds = map(float, re.search(r'Duration: (\d+):(\d+):([\d.]+)', probe).groups())
    duration = hours * 3600 + minutes * 60 + seconds
    run(['-i', str(source), '-map', '0:v:0', '-map_metadata', '-1',
         '-vf', "crop='min(iw,ih)':'min(iw,ih)',scale=512:512:flags=lanczos,setsar=1,fps=24",
         '-an', '-sn', '-dn', '-c:v', 'libx264', '-preset', 'slow', '-crf', '26',
         '-maxrate', '1200k', '-bufsize', '2400k', '-pix_fmt', 'yuv420p',
         '-g', '48', '-threads', '2', '-movflags', '+faststart', str(output / f'{name}.mp4')])
    run(['-i', str(output / f'{name}.mp4'), '-frames:v', '1', '-q:v', '3', str(output / f'{name}.jpg')])
    print(f'{name}: {source.stat().st_size} -> {(output / (name + ".mp4")).stat().st_size} bytes', flush=True)
    return {'src': f'/assets/dreams/{name}.mp4', 'poster': f'/assets/dreams/{name}.jpg',
            'source': source.name, 'duration': duration, 'originalBytes': source.stat().st_size,
            'bytes': (output / f'{name}.mp4').stat().st_size}

with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
    dreams = list(pool.map(encode, enumerate(sources)))

# Tiny previews share one decoder. Every original clip is preserved in full above.
columns, tile = 5, 128
inputs = []
filters = []
for index in range(len(dreams)):
    inputs += ['-stream_loop', '-1', '-i', str(output / f'dream-{index + 1:02}.mp4')]
    filters.append(f'[{index}:v]fps=20,scale={tile}:{tile},setsar=1,setpts=PTS-STARTPTS[v{index}]')
layout = '|'.join(f'{index % columns * tile}_{index // columns * tile}' for index in range(len(dreams)))
filters.append(''.join(f'[v{index}]' for index in range(len(dreams))) + f'xstack=inputs={len(dreams)}:layout={layout}:fill=black[out]')
run([*inputs, '-filter_complex_threads', '2', '-filter_complex', ';'.join(filters), '-map', '[out]',
     '-t', str(max(dream['duration'] for dream in dreams)), '-an', '-c:v', 'libx264', '-preset', 'slow',
     '-crf', '27', '-pix_fmt', 'yuv420p', '-g', '40', '-threads', '2', '-movflags', '+faststart',
     str(output / 'grid.mp4')])
run(['-i', str(output / 'grid.mp4'), '-frames:v', '1', '-q:v', '2', str(output / 'grid.jpg')])
atlas = {'src': '/assets/dreams/grid.mp4', 'poster': '/assets/dreams/grid.jpg', 'columns': columns, 'tile': tile}
(output / 'catalog.js').write_text('// Generated by scripts/prepare-dreams.py.\nexport const dreams = '
    + json.dumps(dreams, indent=2, ensure_ascii=False) + ';\nexport const atlas = ' + json.dumps(atlas) + ';\n')
print(f'Total originals: {sum(dream["originalBytes"] for dream in dreams)}; website media: '
      f'{sum(path.stat().st_size for path in output.iterdir())} bytes', flush=True)
